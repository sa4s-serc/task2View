"""Keep the single-agent skill (Task2View/skill) in step with the pipeline's knowledge.

Copies the catalog YAML the pipeline loads into skill/knowledge/ and generates
skill/references/catalogs.md (viewpoints, needs, roles with their derived priors,
signals, constraints) from the same loader the pipeline uses. Run after any
change to knowledge/data/vb/ or knowledge/data/uml/; tests/test_skill_sync.py fails if the skill is stale.

    .venv/bin/python scripts/sync_skill.py
"""

from __future__ import annotations

import shutil
from pathlib import Path

from task2view.knowledge.catalog import Catalog, load_catalog

CODE = Path(__file__).resolve().parents[1]
SKILL = CODE.parent / "skill"
SOURCE = CODE / "src" / "task2view" / "knowledge" / "data"
COPIED = ["vb/needs.yaml", "vb/viewpoints.yaml", "vb/roles.yaml", "vb/corpus.yaml", "vb/pipeline.yaml",
          "vb/element_roles.yaml", "uml/uml-2.5.1.yaml"]  # copied flat into skill/knowledge/
GOAL_SETS = {"pilot-2026-09": CODE / "tests" / "fixtures" / "pilot_goals.yaml"}
SYSTEM_PATHS = {"progetto-is": "data/Progetto-IS-main-English", "gr10": "data/progetto_ing_software_gr10-main-English"}


def catalogs_markdown(cat: Catalog) -> str:
    out = ["# Catalogs (generated — do not edit)", "",
           "Generated by `code/scripts/sync_skill.py` from the same files the Task2View pipeline loads "
           "(`knowledge/data/vb/`). Copies of the YAML are in [`../knowledge/`](../knowledge/).", ""]

    out += ["## Information needs", "", "| id | category | what the stakeholder must see | example wording |", "|---|---|---|---|"]
    for n in cat.needs.values():
        out.append(f"| `{n.id}` | {n.category} | {n.description} | {', '.join(n.cues)} |")

    out += ["", "## Viewpoints (Views and Beyond, 2nd ed.)", "",
            "*applies when*: empty means generic (every system); otherwise the repository must show one of these signals. "
            "*evidence*: when none of these signals is present, the view is still selected and reported as a declared gap.", "",
            "| id | V&B | family | frames | also covers | applies when | evidence | elements | relations | model kind | max elements (overview / feature / detailed) | overlays |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for v in cat.viewpoints.values():
        caps = " / ".join(str(v.granularity[level]["max_elements"]) for level in ("overview", "feature", "detailed"))
        style = f" (style of `{v.style_of}`)" if v.style_of else ""
        out.append(f"| `{v.id}`{style} | {v.vb_ref} | {v.family} | {', '.join(v.frames)} | {', '.join(v.also_covers) or '—'} | "
                   f"{', '.join(v.applies_when) or 'generic'} | {', '.join(v.evidence) or '—'} | {', '.join(v.element_kinds)} | "
                   f"{', '.join(v.relation_kinds)} | {v.model_kind} | {caps} | {', '.join(v.combine_with) or '—'} |")
    out += ["", f"C&C style order (a selected `cnc-generic` becomes the first applicable style): "
                f"{', '.join(f'`{s}`' for s in cat.cnc_style_priority)}.", ""]

    out += ["## Roles and their priors", "",
            "A prior is used only when the goal states no need (take all needs at the role's highest prior) and to break ties.", "",
            "| id | label | also called | V&B Table 9.1 row | priors (need: weight) |", "|---|---|---|---|---|"]
    for r in cat.roles.values():
        priors = ", ".join(f"{n}: {w:g}" for n, w in sorted(r.priors.items(), key=lambda x: (-x[1], x[0])))
        out.append(f"| `{r.id}` | {r.label} | {', '.join(r.aliases)} | {r.vb_row or 'extension'} | {priors or '—'} |")

    out += ["", "## Repository signals", "", "| signal | meaning |", "|---|---|"]
    out += [f"| `{k}` | {v} |" for k, v in cat.signals.items()]
    out += ["", "## Constraints checked on every view", "", "| constraint | severity | rule |", "|---|---|---|"]
    out += [f"| `{k}` | {v['severity']} | {v['description']} |" for k, v in cat.constraints.items()]
    out += ["", "## Detail level", "",
            f"- `detailed`: the goal enumerates at least {cat.detail_rule['detailed_min_subjects']} subjects.",
            f"- `feature`: at least {cat.detail_rule['feature_min_needs']} primary needs, or exactly one subject.",
            "- `overview`: otherwise.", ""]
    return "\n".join(out)


def goal_sets_markdown() -> str:
    """Goal texts only. Expected views stay out: the skill agent must not see an answer key."""
    import yaml

    out = ["# Goal sets (generated — do not edit)", "",
           "Generated by `code/scripts/sync_skill.py`. The method works for any goal; these are the goal sets used in "
           "experiments so far. Pass each goal **verbatim** as `--goal`, and use the case id as `--run-id` and as the "
           "output folder name.", ""]
    for name, path in GOAL_SETS.items():
        doc = yaml.safe_load(path.read_text(encoding="utf-8"))
        out += [f"## {name}", ""]
        by_system: dict[str, list[tuple[str, str]]] = {}
        for case_id, case in doc["cases"].items():
            by_system.setdefault(case.get("system", ""), []).append((case_id, case["goal"]))
        for system, cases in by_system.items():
            out += [f"### {system} — `{SYSTEM_PATHS.get(system, system)}`", ""]
            for case_id, goal in cases:
                out += [f"**{case_id}**", "", "```text", goal, "```", ""]
    return "\n".join(out)


def sync(skill: Path = SKILL) -> list[str]:
    changed = []
    (skill / "knowledge").mkdir(parents=True, exist_ok=True)
    for name in COPIED:
        src, dst = SOURCE / name, skill / "knowledge" / Path(name).name
        if not dst.exists() or dst.read_bytes() != src.read_bytes():
            shutil.copyfile(src, dst)
            changed.append(str(dst))
    for md, text in ((skill / "references" / "catalogs.md", catalogs_markdown(load_catalog())),
                     (skill / "references" / "goal-sets.md", goal_sets_markdown())):
        if not md.exists() or md.read_text(encoding="utf-8") != text:
            md.parent.mkdir(parents=True, exist_ok=True)
            md.write_text(text, encoding="utf-8")
            changed.append(str(md))
    return changed


if __name__ == "__main__":
    for path in sync():
        print("updated", path)
